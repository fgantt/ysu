import { cleanup, fireEvent, render } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { SecondaryViewMenu } from './SecondaryViewMenu';
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
it('opens View options directly, displays shortcuts, and closes after selection', () => {
  const onOpen = vi.fn();
  const view = render(<SecondaryViewMenu onOpen={onOpen} available={id => id !== 'usi'} />);
  fireEvent.click(view.getByRole('button', { name: 'View' }));
  const item = view.getByRole('menuitem', { name: /Engine Thinking/ });
  expect(item.getAttribute('aria-keyshortcuts')).toBe('Control+Alt+5');
  expect((view.getByRole('menuitem', { name: /USI Monitor/ }) as HTMLButtonElement).disabled).toBe(true);
  fireEvent.click(item);
  expect(onOpen).toHaveBeenCalledWith('thinking');
  expect(view.queryByRole('menuitem', { name: /Engine Thinking/ })).toBeNull();
});
it('uses all shortcuts without requiring an open menu and ignores repeats/unavailable commands', () => {
  const onOpen = vi.fn();
  const view = render(<SecondaryViewMenu onOpen={onOpen} available={id => id !== 'usi'} />);
  for (const number of [1, 2, 3, 4, 5, 6, 8]) fireEvent.keyDown(window, { code: `Digit${number}`, ctrlKey: true, altKey: true });
  expect(onOpen.mock.calls.map(args => args[0])).toEqual(['candidates', 'continuation', 'mate', 'comparison', 'thinking', 'review', 'evaluation']);
  fireEvent.keyDown(window, { code: 'Digit7', ctrlKey: true, altKey: true });
  fireEvent.keyDown(window, { code: 'Digit1', ctrlKey: true, altKey: true, repeat: true });
  expect(onOpen).toHaveBeenCalledTimes(7);
  view.unmount();
  fireEvent.keyDown(window, { code: 'Digit1', ctrlKey: true, altKey: true });
  expect(onOpen).toHaveBeenCalledTimes(7);
});
it('shows Mac shortcuts and supports Escape and outside-click dismissal', () => {
  vi.spyOn(navigator, 'platform', 'get').mockReturnValue('MacIntel');
  const onOpen = vi.fn();
  const view = render(<SecondaryViewMenu onOpen={onOpen} available={() => true} />);
  fireEvent.keyDown(window, { code: 'Digit2', metaKey: true, altKey: true });
  expect(onOpen).toHaveBeenCalledWith('continuation');
  fireEvent.click(view.getByRole('button', { name: 'View' }));
  expect(view.getByText('⌘⌥2')).toBeTruthy();
  fireEvent.keyDown(window, { key: 'Escape' });
  expect(document.activeElement).toBe(view.getByRole('button', { name: 'View' }));
  fireEvent.click(view.getByRole('button', { name: 'View' }));
  fireEvent.pointerDown(document.body);
  expect(view.queryByRole('menu', { name: 'View' })).toBeNull();
});
it('opens outside a clipped parent menu and supports arrow-key navigation', () => {
  const view = render(<div className="compact-menu-popover" style={{ overflow: 'hidden' }}><SecondaryViewMenu onOpen={vi.fn()} available={id => id !== 'mate'} /></div>);
  const parent = view.container.querySelector('.compact-menu-popover')!;
  vi.spyOn(parent, 'getBoundingClientRect').mockReturnValue({ left: 650, right: 900, top: 0, bottom: 500, width: 250, height: 500 } as DOMRect);
  const trigger = view.getByRole('button', { name: 'View' });
  vi.spyOn(trigger, 'getBoundingClientRect').mockReturnValue({ left: 660, right: 890, top: 100, bottom: 136, width: 230, height: 36 } as DOMRect);
  fireEvent.keyDown(trigger, { key: 'ArrowRight' });
  const menu = view.getByRole('menu', { name: 'View' });
  expect(menu.parentElement).toBe(document.body);
  expect(parent.contains(menu)).toBe(false);
  expect(Number.parseFloat(menu.style.left)).toBeLessThan(650);
  expect(document.activeElement).toBe(view.getByRole('menuitem', { name: /Candidate Moves/ }));
  fireEvent.keyDown(menu, { key: 'ArrowDown' });
  expect(document.activeElement).toBe(view.getByRole('menuitem', { name: /Continuation Board/ }));
  fireEvent.keyDown(menu, { key: 'ArrowDown' });
  expect(document.activeElement).toBe(view.getByRole('menuitem', { name: /Engine Comparison/ }));
  fireEvent.keyDown(menu, { key: 'ArrowLeft' });
  expect(view.queryByRole('menu')).toBeNull();
  expect(document.activeElement).toBe(trigger);
});
